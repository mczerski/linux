static int m88tc6800_write_reg(struct m88tc6800_priv *priv, u8 reg, u8 val)
{
	u8 buf[] = { reg, val };
	struct i2c_msg msg = { .addr = priv->config.addr, .flags = 0,
			       .buf = buf, .len = 2 };
	int ret;

	ret = i2c_transfer(priv->i2c, &msg, 1);
	if (ret == 1) {
		ret = 0;
	} else {
		dev_warn(&priv->i2c->dev, "i2c wr failed=%d reg=%02x ", ret, reg);
		ret = -EREMOTEIO;
	}
	return ret;
}

static int m88tc6800_write_data(struct m88tc6800_priv *priv, u8 *data, size_t len)
{
	struct i2c_msg msg = { .addr = priv->config.addr, .flags = 0,
			       .buf = data, .len = len };
	int ret;

	ret = i2c_transfer(priv->i2c, &msg, 1);
	if (ret == 1) {
		ret = 0;
	} else {
		dev_warn(&priv->i2c->dev, "i2c data failed=%d ", ret);
		ret = -EREMOTEIO;
	}
	return ret;
}

static int m88tc6800_read_reg(struct m88tc6800_priv *priv, u8 reg, u8 *val)
{
	
	u8 buf[1] = { reg };
	struct i2c_msg msg[] = {
		{ .addr = priv->config.addr, .flags = 0,
		  .buf = buf, .len = 1 },
		{ .addr = priv->config.addr, .flags = I2C_M_RD,
		  .buf = val, .len = 1 },
	};
	int ret;

	ret = i2c_transfer(priv->i2c, msg, 2);
	if (ret == 2) {
		ret = 0;
	} else {
		dev_warn(&priv->i2c->dev, "i2c rd failed=%d reg=%02x ", ret, reg);
		ret = -EREMOTEIO;
	}
	return ret;
}

static int m88tc6800_set_reg_bits(struct m88tc6800_priv *priv, u8 reg, u8 val, u8 begin_bit, u8 end_bit)
{
	u8 val_mask = ((1 << (end_bit - begin_bit + 1)) - 1) << begin_bit;
	u8 reg_data;
	int ret;

	ret = m88tc6800_read_reg(priv, reg, &reg_data);
	if (ret)
		return ret;

	reg_data &= ~val_mask;
	val = (val << begin_bit) & val_mask;
	reg_data |= val;

  ret = m88tc6800_write_reg(priv, reg, reg_data);
  return ret;
}

uint32_t m88tc6800_expand_reg_bits(struct m88tc6800_priv *priv, u8 reg_expand, u8 reg, u8 val, u8 start_bit, u8 end_bit)
{
  byte reg_data_00;
  uint8_t reg_addr_00 = reg_expand;
  uint8_t reg_data_01 = reg;
  int extraout_r2 = val;
  uint extraout_r3 = end_bit;
  uint uVar1;
  uint uVar2;
  uint uVar3;
  byte local_31 [5];
  
  uVar2 = (uint)start_bit;
  local_31[0] = 0;
  uVar1 = uVar2;
  uVar3 = extraout_r3;
  if (uVar2 <= extraout_r3) {
    uVar1 = extraout_r3;
    uVar3 = uVar2;
  }
  uVar3 = (uVar3 + 7) - uVar1;
  m88tc6800_write_reg(priv, reg_addr_00,reg_data_01);
  m88tc6800_read_reg(priv, reg_addr_00 + 0x1,local_31);
  reg_data_00 = (local_31[0] & ~(byte)((int)(0xff << (uVar3 & 0xff) & 0xffU) >> (7 - uVar1 & 0xff))) |
                (byte)((int)(extraout_r2 << (uVar3 & 0xff) & 0xffU) >> (7 - uVar1 & 0xff));
  local_31[0] = reg_data_00;
  m88tc6800_write_reg(priv, reg_addr_00,reg_data_01);
  m88tc6800_write_reg(priv, reg_addr_00 + 0x1,reg_data_00);
  return 0;
}

static int m88tc6800_write_fw(struct m88tc6800_priv *priv)
{
	u8 expected_fw_ver = 0xc;
	u8 reg_data;
	u8 buf[65] = {0xc0};
	int ret;
	size_t i;

	dev_info(&priv->i2c->dev, "M88TC6800 uploading firmware\n");

	m88tc6800_set_reg_bits(priv, 0x05, 1, 2, 2);
	m88tc6800_write_reg(priv, 0xc2, 1);

	for (i = 0; i < sizeof(m88tc6800_fw); i += (sizeof(buf) - 1)) {
		size_t len = min(sizeof(buf) - 1, sizeof(m88tc6800_fw) - i);
		memcpy(&buf[1], &m88tc6800_fw[i], len);
		ret = m88tc6800_write_data(priv, buf, len + 1);
		if (ret)
			return ret;
	}

	m88tc6800_write_reg(priv, 0xc2, 0);

	/* check fw upload status */
	m88tc6800_read_reg(priv, 0xc8, &reg_data);
	dev_info(&priv->i2c->dev, "M88TC6800 fw version=%x\n", reg_data);
	m88tc6800_set_reg_bits(priv, 0x05, 0, 2, 2);

	if (reg_data == expected_fw_ver) {
		priv->mcu_status = true;
		m88tc6800_set_reg_bits(priv, 0x3e, 0, 5, 5);
		return 0;
	}

	dev_err(&priv->i2c->dev, "M88TC6800 fw version mismatch, expected %x\n", expected_fw_ver);
	priv->mcu_status = false;
	return -1;
}

static int m88tc6800_init(struct dvb_frontend *fe)
{
	struct m88tc6800_priv *priv = fe->tuner_priv;
	u8 reg_data;
	int ret;

	if (fe->ops.i2c_gate_ctrl)
		fe->ops.i2c_gate_ctrl(fe, 1);

	ret = m88tc6800_read_reg(priv, 0x3e, &reg_data);
	if (ret)
		goto err;

	if ((reg_data & 0x20) == 0 && priv->mcu_status == true)
		goto done;

	ret = m88tc6800_write_fw(priv);
	if (ret)
		goto err;

done:
	if (fe->ops.i2c_gate_ctrl)
		fe->ops.i2c_gate_ctrl(fe, 0);
	return 0;

err:
	if (fe->ops.i2c_gate_ctrl)
		fe->ops.i2c_gate_ctrl(fe, 0);
	dev_err(&priv->i2c->dev, "%s: failed=%d\n", __func__, ret);
	return ret;
}

